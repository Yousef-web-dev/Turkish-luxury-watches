function build(s, i) {
  const m = movementInfo[s.movement];
  const c = categoryInfo[s.category];
  return {
    id: s.id,
    title: s.title,
    tagline: s.tagline,
    category: s.category,
    movement: s.movement,
    price: s.price,
    rating: s.rating,
    reviews: s.reviews,
    description: s.description,
    stock: s.stock,
    stockCount: s.stockCount,
    images: gallery(i),
    look: s.look,
    featured: s.featured,
    isNew: s.isNew,
    order: i,
    specs: [
      { label: "Reference", value: `BH-${1001 + i}` },
      { label: "Case", value: `${s.size} mm diameter, ${s.thick} mm thick` },
      { label: "Case material", value: s.caseMat },
      { label: "Dial", value: s.dialName },
      { label: "Crystal", value: c.crystal },
      { label: "Movement", value: `${s.movement}, ${m.caliber}` },
      { label: "Power reserve", value: m.reserve },
      { label: "Frequency", value: m.freq },
      { label: "Water resistance", value: s.water ?? c.water },
      { label: "Strap", value: s.strapName },
      { label: "Lug width", value: `${s.size >= 41 ? 22 : s.size >= 37 ? 20 : 18} mm` },
    ],
  };
}

